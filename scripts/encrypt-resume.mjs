#!/usr/bin/env node
/**
 * Encrypts private/personal-resume.json with your unlock code and writes the
 * result to src/lib/personal-resume.enc.ts, which is safe to commit: without
 * the code it is unreadable. The plain JSON and the code never leave your machine.
 *
 *   npm run encrypt-resume              (code read from RESUME_UNLOCK_CODE in .env.local)
 *   npm run encrypt-resume -- <code>    (code given explicitly)
 *
 * Must stay in sync with decryptPersonalResume() in src/lib/personal-resume.ts.
 */
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const ITERATIONS = 600_000;

async function readCode() {
  if (process.argv[2]) return process.argv[2];
  if (process.env.RESUME_UNLOCK_CODE) return process.env.RESUME_UNLOCK_CODE;
  try {
    const env = await readFile(path.join(root, ".env.local"), "utf8");
    return env.match(/^RESUME_UNLOCK_CODE=(.*)$/m)?.[1]?.trim();
  } catch {
    return undefined;
  }
}

const code = await readCode();
if (!code) {
  console.error("No unlock code: set RESUME_UNLOCK_CODE in .env.local or pass it as an argument.");
  process.exit(1);
}
if (code.length < 12) {
  console.warn("Warning: short codes can be guessed offline. Use 12+ characters.");
}

const json = await readFile(path.join(root, "private", "personal-resume.json"), "utf8");
JSON.parse(json); // fail early on a typo rather than shipping broken data

const { subtle } = globalThis.crypto;
const salt = globalThis.crypto.getRandomValues(new Uint8Array(16));
const iv = globalThis.crypto.getRandomValues(new Uint8Array(12));
const baseKey = await subtle.importKey("raw", new TextEncoder().encode(code), "PBKDF2", false, ["deriveKey"]);
const key = await subtle.deriveKey(
  { name: "PBKDF2", hash: "SHA-256", salt, iterations: ITERATIONS },
  baseKey,
  { name: "AES-GCM", length: 256 },
  false,
  ["encrypt"],
);
const ciphertext = new Uint8Array(
  await subtle.encrypt({ name: "AES-GCM", iv }, key, new TextEncoder().encode(json)),
);

const b64 = (bytes) => Buffer.from(bytes).toString("base64");
const out = `// Generated by scripts/encrypt-resume.mjs. Do not edit by hand.
// Encrypted personal resume (AES-256-GCM, key from the unlock code via PBKDF2-SHA-256).
// Safe to commit: unreadable without the code.
export const encryptedPersonalResume = {
  version: 1,
  iterations: ${ITERATIONS},
  salt: "${b64(salt)}",
  iv: "${b64(iv)}",
  data: "${b64(ciphertext)}",
} as const;
`;
await writeFile(path.join(root, "src", "lib", "personal-resume.enc.ts"), out);
console.log(`Encrypted ${json.length} bytes into src/lib/personal-resume.enc.ts`);
